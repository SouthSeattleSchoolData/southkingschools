// Turns the checked-in federal Civil Rights Data Collection extracts into tools/crdc-data.js,
// which the data build imports (no network needed: the CRDC comes out every two years).
//
//   tools/raw/crdc_2023_24.csv  civilrightsdata.ed.gov 2023-24 public-use file (released Aug 2026),
//                               school rows for our districts keyed by 12-digit NCES ID
//   tools/raw/crdc_2021_22.csv  Urban Institute Education Data Portal, CRDC 2021-22, keyed by OSPI code
//   tools/raw/crdc_2023_24_sexual_assault.csv  same 2023-24 file: rape + sexual battery split by staff vs students
//   tools/raw/enrollment_crdc_years.csv  OSPI October enrollment for each CRDC year (ymi4-syjv, q4ba-s3jc),
//                               so incident counts can be shown per 100 students
//
// Run: node tools/snapshot/build-crdc.mjs   (after adding a new year's extract)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { crdcRecord, crdcPrevious } from '../shared.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const csv = (name) => {
  const [head, ...lines] = readFileSync(join(root, 'tools/raw', name), 'utf8').trim().split('\n');
  const h = head.split(',');
  return lines.map((l) => Object.fromEntries(l.split(',').map((v, i) => [h[i], v])));
};
const schools = JSON.parse(readFileSync(join(root, 'data/schools.json'), 'utf8')).schools;
// NCES ID -> OSPI code: from the data file, plus tools/raw/nces_directory.txt for schools the data
// file doesn't have yet (a newly added district, before the first automatic update).
const codeByNces = Object.fromEntries([
  ...readFileSync(join(root, 'tools/raw/nces_directory.txt'), 'utf8').trim().split('\n').map((l) => l.split('|')).filter(([, id]) => id).map(([code, id]) => [id, code]),
  ...schools.filter((s) => s.nces_id).map((s) => [s.nces_id, s.code]),
]);

const split = Object.fromEntries(csv('crdc_2023_24_sexual_assault.csv').map((r) => [r.nces, r]));
const enrollment = Object.fromEntries(csv('enrollment_crdc_years.csv').map((r) => [r.code, r]));
const num = (x) => (x === '' || x == null ? null : Number(x));

const current = {};
for (const r of csv('crdc_2023_24.csv')) {
  const code = codeByNces[r.nces];
  if (!code) continue;
  current[code] = { ...crdcRecord({ ...r, ...split[r.nces] }, '2023-24'), enrollment: num(enrollment[code]?.enrollment_2023_24) };
}
// Quality check: a district whose every school reports exactly as many threats as attacks
// almost certainly copied one figure into both fields. Flag the threats so pages can say so.
const byDistrict = {};
for (const s of schools) if (current[s.code]) (byDistrict[s.district] ??= []).push(current[s.code]);
for (const [district, recs] of Object.entries(byDistrict)) {
  const active = recs.filter((r) => (r.attacks || 0) + (r.threats || 0) > 0);
  if (active.length >= 10 && active.every((r) => r.attacks === r.threats)) {
    recs.forEach((r) => { r.suspect = ['threats']; });
    console.log(`Flagged: ${district} reports identical attack and threat counts at all ${active.length} schools with either.`);
  }
}

const previous = {};
for (const r of csv('crdc_2021_22.csv')) previous[r.code] = crdcPrevious({ ...crdcRecord(r, '2021-22'), enrollment: num(enrollment[r.code]?.enrollment_2021_22) });

const out = `// Generated by tools/snapshot/build-crdc.mjs from tools/raw/crdc_*.csv. Do not edit by hand.
export const CRDC_YEAR = '2023-24';
export const CRDC_PREV_YEAR = '2021-22';
export const CRDC = ${JSON.stringify(current)};
export const CRDC_PREV = ${JSON.stringify(previous)};
`;
writeFileSync(join(root, 'tools/crdc-data.js'), out);
console.log(`CRDC 2023-24: ${Object.keys(current).length} schools; 2021-22: ${Object.keys(previous).length}.`);
